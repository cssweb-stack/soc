"""Validate current SOC sources, built pages, local links and configured redirects.
Original WordPress preservation evidence lives in reference/ and shared reports;
this check follows the reviewed current information architecture.
"""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit,unquote
import re,json,sys
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'_site';prefix=sys.argv[1].rstrip('/') if len(sys.argv)>1 else ''
class Scan(HTMLParser):
 def __init__(self):super().__init__();self.ids=[];self.links=[];self.h1=0;self.main=0;self.desc=False;self.alt=True
 def handle_starttag(self,t,a):
  a=dict(a)
  if 'id' in a:self.ids.append(a['id'])
  self.h1+=t=='h1';self.main+=t=='main'
  if t=='meta' and a.get('name')=='description':self.desc=bool(a.get('content'))
  if t=='img' and 'alt' not in a:self.alt=False
  attr='href' if t in ['a','link'] else 'src' if t in ['img','script','iframe','source'] else None
  if attr and a.get(attr):self.links.append(a[attr])
def scan(s):
 p=Scan();p.feed(s);return p
sources={}
for p in (ROOT/'src').rglob('*.html'):
 s=p.read_text();m=re.search(r'^permalink:\s*["\']([^"\']+)',s,re.M)
 if not m:raise ValueError('Missing source permalink '+str(p))
 url=m[1];rel=url.lstrip('/')+('index.html' if url.endswith('/') else '')
 if rel in sources:raise ValueError('Duplicate permalink '+url)
 sources[rel]=p
migration=json.loads((ROOT.parent/'css-shared/src/data/units/soc/url-migration.json').read_text())
redirects={e['from'].lstrip('/')+('index.html' if e['from'].endswith('/') else ''):e for e in migration['redirects']}
files={str(p.relative_to(OUT)):p for p in OUT.rglob('*.html')};errors=[]
if set(files)!=set(sources)|set(redirects):errors.append('Output set differs from source/redirect inventory: '+str(set(files)^(set(sources)|set(redirects))))
parsed={k:scan(p.read_text()) for k,p in files.items()}
for rel,p in files.items():
 s=parsed[rel];raw=p.read_text()
 if rel in sources:
  if s.h1!=1 or s.main!=1:errors.append(rel+': expected one H1 and main')
  if len(s.ids)!=len(set(s.ids)):errors.append(rel+': duplicate IDs')
  if not s.desc or not s.alt:errors.append(rel+': missing description or image alt')
  if any(x in raw for x in ['{{','{%','[custom-twitter','fl-builder','fl-accordion']):errors.append(rel+': template/plugin leftovers')
 if rel in redirects:
  if not raw.startswith('<!-- Generated by shared URL migration;'):errors.append(rel+': missing generated marker')
  if '<meta http-equiv="refresh" content="0;' not in raw:errors.append(rel+': missing immediate redirect')
 for value in s.links:
  u=urlsplit(value)
  if u.scheme or u.netloc:continue
  path=unquote(u.path)
  if path.startswith('/'):
   if prefix and not path.startswith(prefix+'/'):errors.append(rel+': missing prefix '+value);continue
   target=OUT/path[len(prefix):].lstrip('/')
  else:target=p.parent/path if path else p
  if target.is_dir():target=target/'index.html'
  if not target.exists():errors.append(rel+': missing target '+value);continue
  if target.suffix=='.html' and u.fragment:
   targetrel=str(target.resolve().relative_to(OUT.resolve()))
   if unquote(u.fragment) not in parsed[targetrel].ids:errors.append(rel+': missing anchor '+value)
# CSS assets must resolve in both root and GitHub project builds.
for css in OUT.rglob('*.css'):
 for value in re.findall(r'url\([\"\']?([^\"\')]+)',css.read_text()):
  if value.startswith(('data:','http:','https:','#')):continue
  path=urlsplit(value).path
  target=OUT/path[len(prefix):].lstrip('/') if path.startswith('/') else css.parent/path
  if not target.exists():errors.append(str(css.relative_to(OUT))+': missing CSS asset '+value)
if errors:
 print('\n'.join(errors));sys.exit(1)
print(f'Checked {len(sources)} current content pages, {len(redirects)} redirects, internal links/anchors, image alt attributes and CSS assets; {len(migration.get("unresolved",[]))} routing decisions remain explicit.')
